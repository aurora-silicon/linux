struct avd_vp9_fp_layout {
	size_t size;
	u32 tiles;
	u16 cols, rows;
};

static const struct avd_vp9_fp_layout vp9_layouts[] = {
	[AVD_VP9_FP_V3] = { .size = 0x24aa4, .tiles = 0xab8 },
	[AVD_VP9_FP_BORAGE] = {
		.size = 0x1130d0, .cols = 0x218, .rows = 0x21a,
	},
	/* TODO: t-3862 Daybreak per-SoC ledger; no V3/Borage aliasing. */
	[AVD_VP9_FP_T8112] = {},
	[AVD_VP9_FP_T8140] = {},
	/* t-3862 FP-TABLES 2.3: LilyD is not the public Viola/V3 layout. */
	[AVD_VP9_FP_T6000] = {},
};

bool avd_vp9_needs_counts(u32 flags)
{
	return (flags & V4L2_VP9_FRAME_FLAG_REFRESH_FRAME_CTX) &&
	       !(flags & V4L2_VP9_FRAME_FLAG_PARALLEL_DEC_MODE);
}

/* V3 header: index in the legacy LSR/no-pipe-state instruction header -> fp.
 * DMA configuration words are generated by firmware, not copied from Linux.
 * The probability block is 1905 bytes plus three bytes of zero alignment.
 * probs.py calls bytes 0..9 padding; the open backend uses them for segmentation.
 */
static const struct {
	u16 word, offset;
} v3_header[] = {
	{ 0, 0x030 }, { 1, 0x034 }, { 2, 0x028 }, { 3, 0x03c },
	{ 4, 0x038 }, { 5, 0x02c }, { 6, 0x040 },
	{ 7, 0x050 }, { 8, 0x054 }, { 9, 0x058 }, { 10, 0x05c },
	{ 11, 0x060 }, { 12, 0x064 }, { 13, 0x068 }, { 14, 0x06c },
	{ 15, 0x098 }, { 19, 0x104 }, { 20, 0x118 },
	{ 21, 0x108 }, { 22, 0x10c }, { 23, 0x110 }, { 24, 0x114 },
	{ 25, 0x04c }, { 26, 0x044 }, { 27, 0x048 },
	{ 31, 0x0e8 }, { 32, 0x0ec }, { 33, 0x0f0 },
	{ 34, 0x0f4 }, { 35, 0x0f8 }, { 36, 0x100 },
	{ 38, 0x11c }, { 39, 0x120 }, { 40, 0x124 }, { 41, 0x128 },
	{ 42, 0x0fc }, { 43, 0x168 }, { 44, 0x170 },
	{ 45, 0x16c }, { 46, 0x174 }, { 48, 0x094 },
};

static int pack_v3(struct avd_frame *f, const struct v4l2_ctrl_vp9_frame *frame,
		   dma_addr_t probs_addr)
{
	u8 *fp = f->fp->cpu;
	const u8 *prog;
	bool intra = frame->flags & (V4L2_VP9_FRAME_FLAG_KEY_FRAME |
				    V4L2_VP9_FRAME_FLAG_INTRA_ONLY);
	u32 tiles;
	u32 header_words = intra ? 49 : 73;

	if (frame->tile_cols_log2 > 4 || frame->tile_rows_log2 > 2 ||
	    !f->prog || !f->prog->cpu)
		return -EINVAL;
	prog = f->prog->cpu;
	tiles = (1U << frame->tile_cols_log2) * (1U << frame->tile_rows_log2);
	if (f->prog_words < header_words + tiles * 5 || probs_addr >> 40)
		return -EINVAL;
	put_unaligned_le32(2, fp + 4);
	put_unaligned_le32(0x24aa4, fp + 0x0c);
	put_unaligned_le32(0xdeadcafe, fp + 0x14);
	put_unaligned_le32(0x101, fp + 0x18);
	put_unaligned_le32(0xaa4, fp + 0x20);
	for (unsigned int i = 0; i < ARRAY_SIZE(v3_header); i++)
		memcpy(fp + v3_header[i].offset, prog + v3_header[i].word * 4, 4);
	put_unaligned_le32(probs_addr >> 8, fp + 0x104);
	put_unaligned_le32(0x240, fp + 0xe0);
	put_unaligned_le32(0x764099, fp + 0x210);
	put_unaligned_le32(0x124111, fp + 0x28c);
	put_unaligned_le32(0x40005, fp + 0xab0);
	if (!intra) {
		for (unsigned int ref = 0; ref < 3; ref++) {
			const u8 *r = prog + (52 + ref * 7) * 4;

			memcpy(fp + 0x9c + ref * 4, r, 4);
			memcpy(fp + 0x70 + ref * 4, r + 4, 4);
			memcpy(fp + 0x7c + ref * 4, r + 8, 4);
			for (unsigned int plane = 0; plane < 4; plane++)
				memcpy(fp + 0x138 + plane * 12 + ref * 4,
				       r + 12 + plane * 4, 4);
		}
	}
	for (unsigned int tile = 0; tile < tiles; tile++) {
		const u8 *t = prog + (header_words + tile * 5) * 4;
		/* fp.py has an explicit zero word before til_ab4_tiles.
		 * Its Construct offset is 0xab8 despite the field label. */
		u8 *out = fp + vp9_layouts[AVD_VP9_FP_V3].tiles + tile * 0x24;

		/* V3 public tile records contain only a low 32-bit address. */
		if (get_unaligned_le32(t) & 0x1fff)
			return -ERANGE;
		memcpy(out, t + 4, 16);
		put_unaligned_le32(tile, out + 0x14);
		put_unaligned_le32(0x40004, out + 0x1c);
	}
	/* pio word, FIFO patching and work records remain unproved. */
	return -EOPNOTSUPP;
}

static int pack_borage(struct avd_frame *f,
			const struct v4l2_ctrl_vp9_frame *frame)
{
	u32 cols, rows;
	u8 *fp = f->fp->cpu;

	if (frame->tile_cols_log2 > 6 || frame->tile_rows_log2 > 2)
		return -EINVAL;
	cols = 1U << frame->tile_cols_log2;
	rows = 1U << frame->tile_rows_log2;
	if (cols * rows > 256)
		return -EINVAL;
	put_unaligned_le16(cols, fp + vp9_layouts[AVD_VP9_FP_BORAGE].cols);
	put_unaligned_le16(rows, fp + vp9_layouts[AVD_VP9_FP_BORAGE].rows);
	/* No inferred offsets for syntax, references or Profile 2 bit depth. */
	return -EOPNOTSUPP;
}

int avd_vp9_pack_fp(struct avd_ctx *ctx, struct avd_frame *f,
		    const struct v4l2_ctrl_vp9_frame *frame,
		    const struct v4l2_ctrl_vp9_compressed_hdr *hdr,
		    const void *probs, dma_addr_t probs_addr)
{
	enum avd_vp9_fp_generation gen = ctx->dev->variant->vp9_fp_generation;
	const struct avd_vp9_fp_layout *layout;

	if ((unsigned int)gen >= ARRAY_SIZE(vp9_layouts) || !vp9_layouts[gen].size)
		return -EOPNOTSUPP;
	layout = &vp9_layouts[gen];
	if (!f->fp || !f->fp->cpu || f->fp->size < layout->size)
		return -ENOSPC;
	memset(f->fp->cpu, 0, layout->size);
	if (gen == AVD_VP9_FP_V3)
		return pack_v3(f, frame, probs_addr);
	return pack_borage(f, frame);
}

/* Only the proved Borage descriptor words are filled. The unknown address
 * packing at +0x2c/+0x34 must be settled before this can return success.
 */
int avd_vp9_pack_cmd(struct avd_ctx *ctx, struct avd_frame *f)
{
	u32 work, base, flags;
	u8 *cmd = (u8 *)f->cmd;
	const u8 *fp;
	u64 addr;

	if (ctx->dev->variant->vp9_fp_generation != AVD_VP9_FP_BORAGE)
		return -EOPNOTSUPP;
	if (!f->fp || !f->fp->cpu || f->fp->size < 0x1130d0)
		return -ENOSPC;
	fp = f->fp->cpu;
	work = get_unaligned_le16(cmd + 6);
	if (work > 3)
		return -EINVAL;
	addr = f->fp->addr;
	/* The proved direct fields are u32; never silently truncate a DVA. */
	if (f->fp->size > U32_MAX || addr > U32_MAX - f->fp->size)
		return -ERANGE;
	base = 0x01483120 + 0x1814 * work;
	flags = get_unaligned_le32(cmd);
	/* [C] fp+0x18/19 -> cmd+0x00 bits 0/1; fp+0x2ac bits 0:6 -> 2:8. */
	flags &= ~0x1ffU;
	flags |= (fp[0x18] & 1) | ((fp[0x19] & 1) << 1) |
		 ((get_unaligned_le32(fp + 0x2ac) & 0x7f) << 2);
	put_unaligned_le32(flags, cmd);
	put_unaligned_le32(base, cmd + 4);
	put_unaligned_le32(base + 8, cmd + 8);
	put_unaligned_le16(get_unaligned_le16(fp + 0x1a), cmd + 0x0c);
	put_unaligned_le32(0x014831a0 + 0x1814 * work, cmd + 0x14);
	put_unaligned_le32(0x01483310 + 0x1814 * work, cmd + 0x18);
	put_unaligned_le32(base + 0x280, cmd + 0x1c);
	put_unaligned_le32(addr + 0x3ac, cmd + 0x20);
	put_unaligned_le32(addr + 0x2b0, cmd + 0x24);
	put_unaligned_le32(addr + 0x394, cmd + 0x28);
	return -EOPNOTSUPP;
}
