"""The M3 Air GPU experiment's scripts (tools/aurora-sep/air-gpu) and --m3-gpu-experiment.

Every script is sourced with AIR_GPU_SOURCE_ONLY=1 and pointed at a fake Mac in a temporary
directory: device tree, EFI variables (plain files), an EFI partition with Limine, limine.conf,
the installed UKI and U-Boot's variable file. Nothing here needs root or an Apple Mac.

OneShotTest covers air-gpu-oneshot.sh: arming one boot, Limine consuming it, --disarm, --check,
and every refusal (each leaves every file as it was). CollectVerdictTest feeds air-gpu-collect.sh
kernel logs for each verdict, CollectRunTest runs it end to end, and JobTest covers
air-gpu-job.sh's checks, records and time limit with a fake python3 (JobVulkanTest runs the real
Vulkan job when AIR_GPU_TEST_VULKAN=1 and a Vulkan device is present). GpuExperimentFlagTest
runs the installer with --m3-gpu-experiment on the fake Mac of test_m3_flow.
"""
