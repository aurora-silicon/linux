class JobVulkanTest(unittest.TestCase):
    """The real job on this machine's Vulkan device, through a prefix holding its driver file."""

    def test_real_job(self):
        icds = sorted(Path("/usr/share/vulkan/icd.d").glob("*.json"))
        drm = [p for p in Path("/sys/class/drm").glob("renderD*") if (p / "device/driver").exists()]
        if not icds or not drm:
            self.skipTest("no Vulkan driver or render node here")
        tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, tmp)
        (tmp / "p/share/vulkan/icd.d").mkdir(parents=True)
        (tmp / "p/lib").mkdir()
