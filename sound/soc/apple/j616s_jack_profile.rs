#[derive(Clone, Copy, PartialEq, Eq)]
pub(crate) enum Route {
    Cout,
    Cin,
}

impl Route {
    pub(crate) fn device(self) -> [u8; 4] {
        match self {
            Self::Cout => *b"cout",
            Self::Cin => *b"cin ",
        }
    }
    pub(crate) fn profile(self) -> &'static [u8; 109] {
        match self {
            Self::Cout => &COUT,
            Self::Cin => &CIN,
        }
    }
    pub(crate) fn channels(self) -> u32 {
        match self {
            Self::Cout => 2,
            Self::Cin => 1,
        }
    }
    pub(crate) fn dma_channel(self) -> u32 {
        match self {
            Self::Cout => 4,
            Self::Cin => 5,
        }
    }
}

/// Exact GetDeviceProp wire record from the qualified EPIC-v2 service.
pub(crate) fn get_request(route: Route, property: u32) -> [u8; 52] {
    let mut request = [0; 52];
    request[4..8].copy_from_slice(&u32::MAX.to_le_bytes());
    request[8..12].copy_from_slice(&0xc3000004u32.to_le_bytes());
    request[32..40].copy_from_slice(&0x30u64.to_le_bytes());
    let mut device = route.device();
    device.reverse();
    request[40..44].copy_from_slice(&device);
    request[44..48].copy_from_slice(&property.to_le_bytes());
    request[48..52].copy_from_slice(&1u32.to_le_bytes());
    request
}

/// The transport has removed the retcode. Refuse short, long or inconsistent replies.
pub(crate) fn property_data(reply: &[u8], expected: usize) -> Option<&[u8]> {
    if reply.len() != expected.checked_add(4)? {
        return None;
    }
    let length = u32::from_le_bytes(reply[..4].try_into().ok()?) as usize;
    (length == expected).then_some(&reply[4..])
}

/// Idle admission never powers or reconfigures the shared jack clock.
pub(crate) fn idle_reply(reply: &[u8]) -> bool {
    property_data(reply, 4) == Some(b"eldi".as_slice())
}

/// Retained coS/cin profiles are compared byte for byte, including unknown fields.
pub(crate) fn profile_reply(route: Route, reply: &[u8]) -> bool {
    property_data(reply, 109) == Some(route.profile().as_slice())
}
