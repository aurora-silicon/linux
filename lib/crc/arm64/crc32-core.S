	/*
	 * Scalar 3-way interleaved CRC, for inputs of at least one block of
	 * 3 * CRC_3WAY_LANE bytes. Each block is split into three contiguous
	 * lanes whose CRCs are computed in parallel, which keeps the CRC unit
	 * busy instead of waiting on the latency of a single dependency chain.
	 * The partial CRCs are merged by advancing the running CRC over one
	 * lane of zero bytes with a 4 x 256 entry table (multiplication by
	 * x^(8 * CRC_3WAY_LANE) modulo the polynomial), so no SIMD registers
	 * are used and the code needs no kernel_neon_begin()/end().
	 *
	 * w0: input CRC at entry, output CRC at exit
	 * x1: pointer to input buffer
	 * x2: number of 3 * CRC_3WAY_LANE byte blocks (at least 1)
	 */
	.set		CRC_3WAY_LANE, 1360

	.macro		crc3shift, crc, part
	and		w10, \crc, #0xff
	ubfx		w11, \crc, #8, #8
	ubfx		w12, \crc, #16, #8
	lsr		w13, \crc, #24
	ldr		w10, [x9, w10, uxtw #2]
	ldr		w11, [x16, w11, uxtw #2]
	ldr		w12, [x17, w12, uxtw #2]
	ldr		w13, [x6, w13, uxtw #2]
	eor		w10, w10, w11
	eor		w12, w12, w13
	eor		w10, w10, \part
	eor		\crc, w10, w12
	.endm

	.macro		crc3way, insn, table, order=le
	bit\order	w0
	adr_l		x9, \table
	add		x16, x9, #1024
	add		x17, x9, #2048
	add		x6, x9, #3072

.Lc\@:	add		x7, in, #CRC_3WAY_LANE
	add		x8, in, #2 * CRC_3WAY_LANE
	mov		w4, wzr
	mov		w5, wzr
	mov		x3, #CRC_3WAY_LANE / 16

.Ld\@:	ldp		x10, x11, [in], #16
	ldp		x12, x13, [x7], #16
	ldp		x14, x15, [x8], #16
	\order		x10, x11, x12, x13, x14, x15
	subs		x3, x3, #1
	\insn		w0, w0, x10
	\insn		w4, w4, x12
	\insn		w5, w5, x14
	\insn		w0, w0, x11
	\insn		w4, w4, x13
	\insn		w5, w5, x15
	b.ne		.Ld\@

	crc3shift	w0, w4
	crc3shift	w0, w5

	mov		in, x8
	subs		len, len, #1
	b.ne		.Lc\@

	bit\order	w0
	ret
	.endm

